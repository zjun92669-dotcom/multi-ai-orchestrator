#!/usr/bin/env python3
"""
Task Ticket Validator

Validates the format and consistency of task tickets generated by the
multi-AI orchestrator dispatcher before assignment to sub-agents.

Usage:
    python task_validator.py --tickets <tickets_json>

Examples:
    python task_validator.py --tickets '[{"id":"T-1","role":"research",...}]'
    python task_validator.py --tickets tickets.json

Input:
    --tickets: JSON file path or JSON string. Each ticket must have:
        - id: unique task identifier (string, format: T-{number})
        - role: one of "research", "execution", "qa"
        - description: what the task involves (string)
        - expected_output: description of expected result (string)
        - dependencies: list of task IDs this task depends on (list of strings, can be empty)
        - write_paths: list of file paths the agent may write to (list of strings, only for execution role)
        - supervisor_id: direct supervisor for the assigned agent (string)
        - assigned_agent: unique WorkBuddy agent name (string)

Output (stdout):
    JSON object with:
        - valid: boolean
        - errors: list of error messages (empty if valid)
        - warnings: list of warning messages
        - ticket_count: number of tickets validated

Exit codes:
    0: all tickets valid
    1: invalid input format
    2: validation errors found
"""

import sys
import json
import argparse
import re


def load_json_arg(arg_value):
    """Load JSON from file path or inline JSON string."""
    if arg_value is None:
        return None
    try:
        return json.loads(arg_value)
    except json.JSONDecodeError:
        try:
            with open(arg_value, 'r', encoding='utf-8') as f:
                return json.load(f)
        except (FileNotFoundError, json.JSONDecodeError) as e:
            print(f"Error: cannot parse JSON argument: {e}", file=sys.stderr)
            sys.exit(1)


VALID_ROLES = {'research', 'execution', 'qa'}
VALID_AGENT_KINDS = {'workbuddy', 'external_cli', 'external_mcp', 'external_http'}
VALID_STRATEGIES = {
    'fixed',
    'random',
    'round-robin',
    'least-load',
    'capability-score',
    'external-first',
    'round_robin',
    'least_load',
    'capability_score',
    'external_first',
}
TASK_ID_PATTERN = re.compile(r'^T-\d+$')


def validate_ticket(ticket, all_ids, errors, warnings):
    """Validate a single task ticket. Returns True if no errors."""
    has_errors = False

    # Check required fields
    required_fields = [
        'id',
        'role',
        'description',
        'expected_output',
        'dependencies',
        'supervisor_id',
        'assigned_agent'
    ]
    for field in required_fields:
        if field not in ticket:
            errors.append(f"Ticket missing required field '{field}': {ticket}")
            has_errors = True

    if has_errors:
        return False

    # Validate ID format
    ticket_id = ticket['id']
    if not isinstance(ticket_id, str) or not TASK_ID_PATTERN.match(ticket_id):
        errors.append(f"Invalid task ID format '{ticket_id}'. Expected format: T-{{number}}")
        has_errors = True

    # Check ID uniqueness
    if ticket_id in all_ids:
        errors.append(f"Duplicate task ID: {ticket_id}")
        has_errors = True
    else:
        all_ids.add(ticket_id)

    # Validate role
    role = ticket['role']
    if role not in VALID_ROLES:
        errors.append(f"Invalid role '{role}' for task {ticket_id}. Must be one of: {VALID_ROLES}")
        has_errors = True

    # Validate description is non-empty
    if not isinstance(ticket['description'], str) or len(ticket['description'].strip()) == 0:
        errors.append(f"Empty description for task {ticket_id}")
        has_errors = True

    # Validate expected_output is non-empty
    if not isinstance(ticket['expected_output'], str) or len(ticket['expected_output'].strip()) == 0:
        errors.append(f"Empty expected_output for task {ticket_id}")
        has_errors = True

    # Validate direct supervisor
    if not isinstance(ticket['supervisor_id'], str) or len(ticket['supervisor_id'].strip()) == 0:
        errors.append(f"Empty supervisor_id for task {ticket_id}")
        has_errors = True

    # Validate assigned agent
    if not isinstance(ticket['assigned_agent'], str) or len(ticket['assigned_agent'].strip()) == 0:
        errors.append(f"Empty assigned_agent for task {ticket_id}")
        has_errors = True

    agent_kind = ticket.get('agent_kind', 'workbuddy')
    if agent_kind not in VALID_AGENT_KINDS:
        errors.append(
            f"Invalid agent_kind '{agent_kind}' for task {ticket_id}. "
            f"Must be one of: {sorted(VALID_AGENT_KINDS)}"
        )
        has_errors = True

    if str(agent_kind).startswith('external_'):
        external_ai_id = ticket.get('external_ai_id')
        if not isinstance(external_ai_id, str) or not external_ai_id.strip():
            errors.append(
                f"External task {ticket_id} must specify external_ai_id"
            )
            has_errors = True

    strategy = ticket.get('dispatch_strategy', 'fixed')
    if strategy not in VALID_STRATEGIES:
        errors.append(
            f"Invalid dispatch_strategy '{strategy}' for task {ticket_id}. "
            f"Must be one of: {sorted(VALID_STRATEGIES)}"
        )
        has_errors = True

    # Validate parent_agent (optional, defaults to supervisor_id)
    parent_agent = ticket.get('parent_agent')
    if parent_agent is not None:
        if not isinstance(parent_agent, str) or len(parent_agent.strip()) == 0:
            errors.append(f"Invalid parent_agent for task {ticket_id}. Must be a non-empty string.")
            has_errors = True

    # Validate dependencies
    deps = ticket.get('dependencies', [])
    if not isinstance(deps, list):
        errors.append(f"Dependencies must be a list for task {ticket_id}")
        has_errors = True
    else:
        for dep in deps:
            if not isinstance(dep, str):
                errors.append(f"Dependency must be a string in task {ticket_id}: {dep}")
                has_errors = True

    # Validate write_paths for execution role
    if role == 'execution':
        write_paths = ticket.get('write_paths', [])
        if not isinstance(write_paths, list):
            errors.append(f"write_paths must be a list for execution task {ticket_id}")
            has_errors = True
        elif len(write_paths) == 0:
            errors.append(f"Execution task {ticket_id} must specify at least one write_path")
            has_errors = True
        else:
            for path in write_paths:
                if not isinstance(path, str) or len(path.strip()) == 0:
                    errors.append(f"Invalid write_path in task {ticket_id}: {path}")
                    has_errors = True
    else:
        # Non-execution tasks should not have write_paths
        if 'write_paths' in ticket and len(ticket['write_paths']) > 0:
            warnings.append(
                f"Task {ticket_id} has role '{role}' but specifies write_paths. "
                f"These will be ignored."
            )

    # Warning: QA tasks should depend on execution tasks
    if role == 'qa' and len(deps) == 0:
        warnings.append(
            f"QA task {ticket_id} has no dependencies. "
            f"QA tasks typically depend on execution tasks."
        )

    return not has_errors


def check_dependency_consistency(tickets, errors, warnings):
    """Check that all dependency references point to existing tasks."""
    all_ids = {t['id'] for t in tickets}
    for ticket in tickets:
        for dep in ticket.get('dependencies', []):
            if dep not in all_ids:
                errors.append(
                    f"Task {ticket['id']} depends on non-existent task: {dep}"
                )


def check_circular_dependencies(tickets, errors):
    """Detect circular dependencies using DFS."""
    id_to_deps = {t['id']: t.get('dependencies', []) for t in tickets}

    def has_cycle(node, visited, stack):
        visited.add(node)
        stack.add(node)
        for neighbor in id_to_deps.get(node, []):
            if neighbor not in id_to_deps:
                continue
            if neighbor not in visited:
                if has_cycle(neighbor, visited, stack):
                    return True
            elif neighbor in stack:
                return True
        stack.discard(node)
        return False

    visited = set()
    for ticket_id in id_to_deps:
        if ticket_id not in visited:
            if has_cycle(ticket_id, visited, set()):
                errors.append(f"Circular dependency detected involving task: {ticket_id}")
                return


def main():
    parser = argparse.ArgumentParser(
        description='Validate task tickets for multi-AI orchestrator'
    )
    parser.add_argument(
        '--tickets',
        required=True,
        help='JSON file path or inline JSON string of ticket list'
    )

    args = parser.parse_args()

    tickets = load_json_arg(args.tickets)

    if not isinstance(tickets, list) or len(tickets) == 0:
        print(json.dumps({
            'valid': False,
            'errors': ['Tickets must be a non-empty list'],
            'warnings': [],
            'ticket_count': 0
        }, indent=2, ensure_ascii=False))
        sys.exit(1)

    errors = []
    warnings = []
    all_ids = set()

    for ticket in tickets:
        validate_ticket(ticket, all_ids, errors, warnings)

    # Cross-ticket validation
    check_dependency_consistency(tickets, errors, warnings)
    check_circular_dependencies(tickets, errors)

    result = {
        'valid': len(errors) == 0,
        'errors': errors,
        'warnings': warnings,
        'ticket_count': len(tickets)
    }

    print(json.dumps(result, indent=2, ensure_ascii=False))

    if errors:
        sys.exit(2)
    else:
        sys.exit(0)


if __name__ == '__main__':
    main()
